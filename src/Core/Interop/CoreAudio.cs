[StructLayout(LayoutKind.Sequential)]
internal struct PROPERTYKEY
{
    public Guid fmtid;
    public int pid;

    public PROPERTYKEY(string fmt, int id)
    {
        fmtid = new Guid(fmt);
        pid = id;
    }
}

